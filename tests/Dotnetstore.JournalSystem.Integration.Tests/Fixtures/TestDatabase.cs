using Dotnetstore.JournalSystem.Host.Extensions;
using Microsoft.AspNetCore.Builder;
using Microsoft.Data.SqlClient;
using OrganizationExtensions = Dotnetstore.JournalSystem.Api.Organization.Extensions.HostApplicationBuilderExtensions;

namespace Dotnetstore.JournalSystem.Integration.Tests.Fixtures;

internal static class TestDatabase
{
    /// <summary>
    /// Creates the database and the message tables. The Host needs both before it can start, so this cannot go
    /// through the Host under test.
    /// </summary>
    internal static async Task ProvisionAsync(string connectionString, CancellationToken cancellationToken)
    {
        await ExecuteOnMasterAsync(connectionString, "CREATE DATABASE [{0}];", cancellationToken);

        var builder = WebApplication.CreateBuilder();
        builder.Configuration["ConnectionStrings:" + OrganizationExtensions.DatabaseConnectionName] = connectionString;
        builder.AddJournalMessaging();
        await using var app = builder.Build();
        await app.Services.InitializeMessagingDatabaseAsync(cancellationToken);
    }

    [System.Diagnostics.CodeAnalysis.SuppressMessage("Security", "CA2100", Justification = "Fixed statements; the database name is generated by the test fixture from a GUID.")]
    internal static async Task ExecuteOnMasterAsync(string connectionString, string statement, CancellationToken cancellationToken)
    {
        var settings = new SqlConnectionStringBuilder(connectionString);
        var databaseName = settings.InitialCatalog;
        settings.InitialCatalog = "master";

        await using var connection = new SqlConnection(settings.ConnectionString);
        await connection.OpenAsync(cancellationToken);
        await using var command = connection.CreateCommand();
        command.CommandText = string.Format(System.Globalization.CultureInfo.InvariantCulture, statement, databaseName);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }
}
